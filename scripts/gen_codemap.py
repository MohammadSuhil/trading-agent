"""Generate docs/CODEMAP.md -- every public symbol, its signature, one line of why.

The map exists to make agent sessions cheap. Opening a 600-line module to learn
one function's signature puts all 600 lines into the conversation, and in an
agent loop that context is re-sent on every later turn until the session ends.
A one-line entry here answers the same question for ~1% of the tokens.

A map that drifts is worse than no map: it states a signature with the authority
of documentation while the code says otherwise. Three guards keep it honest --
it is generated (never hand-edited), a pre-commit hook regenerates it, and
`tests/test_codemap.py` fails the build if the committed file differs from what
this script would write now.

Usage:
    uv run --frozen python scripts/gen_codemap.py           # rewrite the file
    uv run --frozen python scripts/gen_codemap.py --check   # exit 1 if stale
"""
from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "CODEMAP.md"

#: Source roots, in reading order: dependencies before their dependents.
SOURCE_ROOTS: tuple[str, ...] = (
    "packages/core/src",
    "packages/datafeed/src",
    "packages/quant/src",
    "packages/ledger/src",
    "packages/llm/src",
    "packages/news/src",
    "apps/api/src",
    "packages/cli/src",
)

#: Signatures longer than this are cut. A 300-character signature costs more to
#: read than it saves, and the full one is a single targeted Read away.
MAX_SIG = 160

HEADER = """\
# Code map

> **Generated by `scripts/gen_codemap.py` -- do not edit by hand.** A pre-commit
> hook regenerates it and `tests/test_codemap.py` fails if it is stale.

Every public module, class and function with its signature and the first line of
its docstring. **Look things up here before opening a source file**; open the
file only for the symbol you are about to change. Private names (`_x`) are
omitted. Package-level orientation lives in each package's `CONTEXT.md`.
"""


def _first_line(node: ast.AST) -> str:
    """First prose line of the docstring. Doctest lines are skipped: `>>> f(1)`
    tells a reader nothing a signature does not.

    >>> src = "def f():\\n    '''>>> f()\\n    1\\n\\n    Why.'''"
    >>> _first_line(ast.parse(src).body[0])
    'Why.'
    """
    doc = ast.get_docstring(node, clean=True) or ""
    lines = [ln.strip() for ln in doc.splitlines() if ln.strip()]
    i = 0
    while i < len(lines) and lines[i].startswith(">>>"):
        i += 2  # the example and its expected output
    return lines[i] if i < len(lines) else ""


def _signature(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    """Render `name(args) -> ret` from the AST, without importing the module.

    Importing would execute module-level code (polars, ClickHouse clients) just
    to read a signature, and would make the map depend on the environment.

    >>> tree = ast.parse("def f(a: int, *, b: str = 'x') -> bool: ...")
    >>> _signature(tree.body[0])
    "f(a: int, *, b: str='x') -> bool"
    """
    args = ast.unparse(fn.args)
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""
    prefix = "async " if isinstance(fn, ast.AsyncFunctionDef) else ""
    sig = f"{prefix}{fn.name}({args}){ret}"
    return sig if len(sig) <= MAX_SIG else sig[: MAX_SIG - 3] + "..."


def _is_public(name: str) -> bool:
    return not name.startswith("_")


def _entry(sig: str, doc: str, indent: str = "") -> str:
    return f"{indent}- `{sig}`" + (f" -- {doc}" if doc else "")


def _route(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    """`GET /api/x ` for a FastAPI handler, else empty. The route is what a
    caller searches for; the handler's Python name rarely is."""
    for dec in fn.decorator_list:
        if (isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute)
                and dec.func.attr in {"get", "post", "put", "delete", "patch"}
                and dec.args and isinstance(dec.args[0], ast.Constant)):
            return f"{dec.func.attr.upper()} {dec.args[0].value} "
    return ""


def _is_fn(node: ast.AST) -> bool:
    return isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and _is_public(node.name)


def _class_lines(node: ast.ClassDef) -> list[str]:
    bases = ", ".join(ast.unparse(b) for b in node.bases)
    lines = [_entry(f"class {node.name}" + (f"({bases})" if bases else ""), _first_line(node))]
    lines += [_entry(_signature(m), _first_line(m), indent="  ") for m in node.body if _is_fn(m)]
    return lines


def render_module(path: Path, rel: str) -> list[str]:
    """Lines for one module; empty when it has nothing public to show."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=rel)
    body: list[str] = []
    for node in tree.body:
        if _is_fn(node):
            body.append(_entry(_route(node) + _signature(node), _first_line(node)))
        elif isinstance(node, ast.ClassDef) and _is_public(node.name):
            body += _class_lines(node)
    mod_doc = _first_line(tree)
    if not body and not mod_doc:
        return []
    lines = [f"### `{rel}`", ""]
    if mod_doc:
        lines += [mod_doc, ""]
    return lines + body + [""]


def render() -> str:
    out = [HEADER]
    for root in SOURCE_ROOTS:
        base = ROOT / root
        files = sorted(p for p in base.rglob("*.py") if "__pycache__" not in p.parts) if base.exists() else []
        sections: list[str] = []
        for p in files:
            sections += render_module(p, p.relative_to(ROOT).as_posix())
        pkg = root.removesuffix("/src")
        out.append(f"## {pkg}\n")
        out.append("\n".join(sections) if sections else "_Nothing built yet._\n")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/CODEMAP.md is stale")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/CODEMAP.md is stale: run scripts/gen_codemap.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
